interface IOPointProps {
    point: ioPointType;
    onUpdateValue: (id: string, value: any) => void;
}

const IOPointComponent: React.FC<IOPointProps> = ({ point, onUpdateValue }) => {
    const isDigital = point.point_type.type.startsWith('D');
    const isInput = point.point_type.type.endsWith('I');

    const handleDigitalToggle = () =>
        onUpdateValue(point.id, !point.point_value);

    const handleAnalogChange = (e: React.ChangeEvent<HTMLInputElement>) => {
        const value = e.target.value;
        if (value === '') {
            onUpdateValue(point.id, ''); // Or 0, depending on desired behavior
        } else {
            const numberValue = Number(value);
            if (!isNaN(numberValue)) {
                onUpdateValue(point.id, numberValue);
            }
        }
    };

    return (
        <div className="flex items-center justify-between gap-2 px-3 py-2 bg-gray-50 rounded-lg min-h-[48px]">
            <div className="flex items-center gap-2">
                <span
                    className={`p-1 rounded-full ${isDigital ? 'bg-blue-200 text-blue-800' : 'bg-purple-200 text-purple-800'}`}
                >
                    {isDigital ? (
                        isInput ? (
                            <InputIcon />
                        ) : (
                            <OutputIcon />
                        )
                    ) : (
                        <SignalIcon />
                    )}
                </span>
                <span className="text-sm font-medium text-gray-700 truncate">
                    {point.point_type.label}
                </span>
            </div>
            {isDigital ? (
                <button
                    onClick={isInput ? undefined : handleDigitalToggle}
                    type="button"
                    className={`h-6 w-12 rounded-full p-0.5 transition-colors duration-200 relative flex items-center justify-center ${isInput ? 'bg-gray-200 cursor-not-allowed' : point.point_value ? 'bg-green-500' : 'bg-gray-400'}`}
                    disabled={isInput}
                >
                    <div
                        className={`h-5 w-5 rounded-full bg-white shadow-md transition-transform duration-200 ${point.point_value ? 'translate-x-3' : '-translate-x-3'}`}
                    ></div>
                </button>
            ) : (
                <div className="flex items-center gap-1 w-full">
                    <input
                        type="number"
                        value={point.point_value as number}
                        onChange={handleAnalogChange}
                        disabled={isInput}
                        min={-100}
                        max={100}
                        step={0.1}
                        className={`w-16 p-1 text-sm rounded-md text-center border focus:outline-none focus:ring-2 focus:ring-blue-500 ${isInput ? 'bg-gray-200 text-gray-500 cursor-not-allowed' : 'bg-white text-gray-800 border-gray-300'}`}
                    />
                </div>
            )}
        </div>
    );
};

interface ModuleModalProps {
    isOpen: boolean;
    onClose: () => void;
    module: ioModuleType | null;
    onSave: (updatedModule: ioModuleType) => void;
}
const ModuleModal: React.FC<ModuleModalProps> = ({
    isOpen,
    onClose,
    module,
    onSave,
}) => {
    if (!isOpen || !module) return null;

    // Keep a reference to the initial module to avoid unnecessary re-renders
    const initialModuleRef = useRef(module);

    // Use formData state to manage form inputs
    const [formData, setFormData] = useState(module);

    const handleInputChange = (e: React.ChangeEvent<HTMLInputElement>) => {
        const { name, value } = e.target;
        setFormData((prev) => ({ ...prev, [name]: value }));
    };

    const handleTypeChange = (e: React.ChangeEvent<HTMLSelectElement>) => {
        const selectedTypeName = e.target.value;
        const newType = ioModuleTypes.find((t) => t.name === selectedTypeName);

        if (newType) {
            setFormData((prev) => {
                // Check if the selected type is actually different from the current one
                if (prev.type.name === newType.name) {
                    return prev; // No change, do not re-render
                }

                // Create a new array of points only if the type has changed
                const newPoints = newType.points.map((p) => ({
                    id: uuidv4(), // Generate a new ID for each point
                    point_type: p, // Assign the correct point type
                    point_value:
                        p.type === 'DO'
                            ? false
                            : ['AO', 'AI'].includes(p.type)
                              ? 0
                              : false,
                }));

                return {
                    ...prev,
                    type: newType,
                    points: newPoints,
                };
            });
        }
    };

    const handleUpdatePointValue = (pointId: string, value: any) => {
        setFormData((prev) => ({
            ...prev,
            points: prev.points.map((p) =>
                // Correct the property name from `value` to `point_value`
                p.id === pointId ? { ...p, point_value: value } : p
            ),
        }));
    };

    const handleSave = () => {
        onSave(formData);
        onClose();
    };

    return (
        <Modal onClose={onClose} isOpen={isOpen} modalTitle="Configure Module">
            <div className="flex-grow">
                <form
                    onSubmit={(e) => {
                        e.preventDefault();
                        handleSave();
                    }}
                    className="flex flex-col "
                >
                    <div className="mb-4">
                        <label className="block text-r2-dark-modal-subtext font-semibold mb-1">
                            Module Name:
                        </label>
                        <input
                            type="text"
                            name="name"
                            value={formData.name}
                            onChange={handleInputChange}
                            className="w-full p-2 rounded-md bg-gray-100 text-gray-800 border border-gray-300 focus:outline-none focus:ring-2 focus:ring-blue-500"
                        />
                    </div>
                    <div className="mb-4">
                        <label className="block text-r2-dark-modal-subtext font-semibold mb-1">
                            Module Type:
                        </label>
                        <select
                            value={formData.type.name}
                            onChange={handleTypeChange}
                            className="w-full p-2 rounded-md bg-gray-100 text-gray-800 border border-gray-300 focus:outline-none focus:ring-2 focus:ring-blue-500"
                        >
                            {ioModuleTypes.map((type) => (
                                <option key={type.name} value={type.name}>
                                    {type.name}
                                </option>
                            ))}
                        </select>
                    </div>
                    <h4 className="text-lg font-bold text-r2-dark-modal-subtext-header mt-6 mb-2">
                        I/O Points
                    </h4>
                    <div className="space-y-2 flex-grow overflow-y-scroll">
                        {formData.points.map((point) => (
                            <IOPointComponent
                                key={point.id}
                                point={point}
                                onUpdateValue={handleUpdatePointValue}
                                // onUpdateValue={() => {}}
                            />
                        ))}
                    </div>
                    <div className="flex justify-end mt-6">
                        <button
                            type="submit"
                            className="px-6 py-2 bg-blue-600 text-white rounded-lg hover:bg-blue-700 transition-colors font-bold"
                        >
                            Save Changes
                        </button>
                    </div>
                </form>
            </div>
        </Modal>
    );
};

