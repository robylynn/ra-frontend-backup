interface DataPointProps {
    dataPoint: opcDataPointType;
    onOpenAlarmModal: (dp: opcDataPointType) => void;
    onDelete: () => void;
    onWrite: (id: string, value: number) => void;
    currentValue: number;
    isAlarmConfigured: boolean;
}

const DataPoint: React.FC<DataPointProps> = ({
    dataPoint,
    onOpenAlarmModal,
    onDelete,
    onWrite,
    currentValue,
    isAlarmConfigured,
}) => {
    const [writeValue, setWriteValue] = useState<number | ''>(currentValue);

    const handleWrite = () => {
        if (writeValue !== '') {
            onWrite(dataPoint.id, Number(writeValue));
        }
    };

    useEffect(() => {
        setWriteValue(currentValue);
    }, [currentValue]);

    return (
        <div className="bg-gray-700 p-3 rounded-xl flex items-center justify-between shadow-inner hover:bg-gray-600 transition-colors">
            <div className="flex items-center space-x-4 flex-grow truncate">
                <div className="flex-shrink-0">
                    {isAlarmConfigured ? (
                        <span className="bg-red-500 w-3 h-3 block rounded-full"></span>
                    ) : (
                        <span className="bg-green-500 w-3 h-3 block rounded-full"></span>
                    )}
                </div>
                <div className="flex flex-col truncate">
                    <div className="text-sm font-bold text-gray-200 truncate">
                        {dataPoint.name}
                    </div>
                    <div className="text-xs font-semibold text-gray-400 truncate">
                        {dataPoint.node_id}
                    </div>
                </div>
            </div>
            <div className="flex items-center space-x-4 flex-shrink-0">
                <div className="text-xs font-semibold text-gray-400">
                    Value:
                </div>
                <div className="text-lg font-bold text-green-400">
                    {currentValue.toFixed(2)}
                </div>
                {dataPoint.is_writable && (
                    <div className="flex items-center space-x-2">
                        <input
                            type="number"
                            value={writeValue}
                            onChange={(e) =>
                                setWriteValue(Number(e.target.value))
                            }
                            className="w-24 p-1 text-sm bg-gray-800 rounded-lg border border-gray-600 focus:outline-none focus:ring-1 focus:ring-blue-500"
                        />
                        <button
                            onClick={handleWrite}
                            className="px-3 py-1 bg-blue-600 text-white text-sm rounded-lg font-semibold hover:bg-blue-700 transition-colors"
                        >
                            Write
                        </button>
                    </div>
                )}
            </div>
            <div className="flex items-center space-x-2 flex-shrink-0 ml-4">
                <button
                    onClick={() => onOpenAlarmModal(dataPoint)}
                    className="p-2 text-yellow-400 hover:text-yellow-300 transition-colors rounded-full"
                >
                    <BellIcon />
                </button>
                <button
                    onClick={onDelete}
                    className="p-2 text-gray-400 hover:text-red-500 transition-colors rounded-full"
                >
                    <TrashIcon />
                </button>
            </div>
        </div>
    );
};

