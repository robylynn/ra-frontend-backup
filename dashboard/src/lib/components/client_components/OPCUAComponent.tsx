interface ServerDiscoveryModalProps {
    isOpen: boolean;
    onClose: () => void;
    onSelectNode: (node: opcDataPointType) => void;
    endpoint: string;
}

const ServerDiscoveryModal: React.FC<ServerDiscoveryModalProps> = ({
    isOpen,
    onClose,
    onSelectNode,
    endpoint,
}) => {
    const [isConnecting, setIsConnecting] = useState(false);
    const [isConnected, setIsConnected] = useState(false);
    const [isBrowsing, setIsBrowsing] = useState(false);
    const [nodeTree, setNodeTree] = useState<Node | null>(null);
    const { showAlert } = useAlert();

    const { dashboardContext } = useContext(DashboardContext);

    const handleConnect = async (endpoint: string) => {
        setIsConnecting(true);
        setNodeTree(null);

        dashboardContext.ros_services.opc_services
            .connect_to_server(endpoint, () => {
                showAlert('Connected to OPC Server', 'success', 'OPC');
                setIsConnected(true);
            })
            .catch((error) => {
                showAlert(`Error: ${error}`, 'error', 'OPC');
                setIsConnected(false);
            })
            .finally(() => setIsConnecting(false));
    };

    const handleBrowse = async () => {
        setIsBrowsing(true);
        const nodes =
            await dashboardContext.ros_services.opc_services.browse_nodes();

        // const parsed_nodes = JSON.parse(nodes) as Node[];
        try {
            const parsed_nodes = opcDataPoints.parse(
                JSON.parse(nodes)
            ) as Node[];
            const node_tree: Node = {
                id: 'root',
                node_id: '',
                name: 'Objects',
                type: IRosTypeR2CInterfacesOpcuaDataTypeType.TYPE_NULL,
                is_writable: false,
                children: parsed_nodes,
            };
            setNodeTree(node_tree);
            setIsBrowsing(false);
        } catch (error) {
            const message = `Error parsing node data from browse; ${error}`;
            logMessage(message, 'error');
            showAlert(message, 'error', 'OPC');
        }
    };

    return (
        <Modal
            isOpen={isOpen}
            onClose={onClose}
            modalTitle="OPC-UA Server Browser"
        >
            <div className="flex flex-col space-y-4">
                <div className="flex items-center space-x-2">
                    <input
                        type="text"
                        className="flex-grow p-3 bg-gray-700 border border-gray-600 rounded-lg focus:outline-none focus:ring-2 focus:ring-blue-500"
                        placeholder="opc.tcp://localhost:4840"
                        defaultValue={endpoint}
                        disabled
                    />
                    <button
                        onClick={() => handleConnect(endpoint)}
                        className="px-4 py-3 rounded-lg bg-blue-600 text-white font-semibold hover:bg-blue-700 transition-colors disabled:opacity-50"
                        disabled={
                            isConnecting ||
                            !dashboardContext?.ros_services?.opc_services
                        }
                    >
                        {isConnecting ? 'Connecting...' : 'Connect'}
                    </button>
                    <button
                        onClick={() => handleBrowse()}
                        className="px-4 py-3 rounded-lg bg-blue-600 text-white font-semibold hover:bg-blue-700 transition-colors disabled:opacity-50"
                        disabled={!isConnected || isConnecting || isBrowsing}
                    >
                        {isBrowsing ? 'Loading...' : 'Browse'}
                    </button>
                </div>
                <div className="bg-gray-700 rounded-lg p-4 h-[50vh] overflow-y-auto">
                    {isConnecting && (
                        <div className="text-center text-gray-400">
                            Connecting to server...
                        </div>
                    )}
                    {nodeTree && (
                        <NodeTree node={nodeTree} onNodeSelect={onSelectNode} />
                    )}
                    {!isConnecting && !nodeTree && !isConnected && (
                        <div className="text-center text-gray-400">
                            Enter a valid endpoint URL and click "Connect".
                        </div>
                    )}
                    {isConnected &&
                        !nodeTree &&
                        !isConnecting &&
                        !isBrowsing && (
                            <div className="text-center text-gray-400">
                                Click "Browse" to browse OPC-UA nodes.
                            </div>
                        )}
                    {isBrowsing && (
                        <div className="text-center text-gray-400">
                            Waiting for browse result...
                        </div>
                    )}
                </div>
            </div>
        </Modal>
    );
};

