"use client";

import CameraStreamContainer from "@/lib/components/client_components/CameraStreamContainer";
import { SimplifiedDashboardHeaderContainer } from "@/lib/components/server_components/SimplifiedDashboardHeaderContainer";
import { cameraMetadataType } from "@/lib/models/autogenerated/configuration_models";
import { DashboardHeaderContainerProps } from "@/lib/models/dashboard_types";

interface CameraStreamPanelProps extends DashboardHeaderContainerProps {
  metadata: cameraMetadataType;
}

export const CameraStreamPanel: React.FC<CameraStreamPanelProps> = ({
  className,
  metadata,
}) => {
  const { variant = "full", camera_id } = metadata;

  return (
    <SimplifiedDashboardHeaderContainer
      title={`Camera ${camera_id || "Stream"}`}
      icon_path={"/icons/device.svg"}
      className={className || ""}
    >
      <div className="w-full h-full bg-gray-900">
        {variant === "compact" && (
          <CameraStreamContainer
            layout="compact"
            showControls={true}
            showSelection={true}
            cameraId={camera_id}
          />
        )}

        {variant === "simple" && (
          <CameraStreamContainer
            layout="full"
            showControls={false}
            showSelection={false}
            cameraId={camera_id}
          />
        )}

        {variant === "full" && (
          <CameraStreamContainer
            layout="full"
            showControls={true}
            showSelection={true}
            cameraId={camera_id}
          />
        )}
      </div>
    </SimplifiedDashboardHeaderContainer>
  );
};

export const CompactCameraStreamPanel = (props: CameraStreamPanelProps) => {
  return (
    <CameraStreamPanel
      {...props}
      metadata={{ ...props.metadata, variant: "compact" }}
    />
  );
};

export const SimpleCameraStreamPanel = (
  props: CameraStreamPanelProps
  // props: Omit<CameraStreamPanelProps, 'variant'>
) => {
  // return <CameraStreamPanel {...props} variant="simple" />;
  return (
    <CameraStreamPanel
      {...props}
      metadata={{ ...props.metadata, variant: "simple" }}
    />
  );
};
