@ui_router.get(
    "/full_config/{client_id}",
    summary="Get Full Configuration for Client",
    status_code=status.HTTP_200_OK,
    response_model=ApiResponse,
)
async def get_full_config(
    client_id: str, request: Request, state: ApiState = Depends(typedAppState)
):
    local_db_pool: AsyncpgPool = state.local_db_pool
    
    ui_config: UiConfiguration = UiConfiguration()
    io_config: IoConfiguration = IoConfiguration()
    opc_config: OpcConfiguration = OpcConfiguration()

    try:
        ui_config = await _get_config(table_name="frontend_configs", client_id=client_id, model=UiConfiguration, local_db_pool=local_db_pool)
    except HTTPException as e:
        if e.status_code == 404:
            logger.warning(f"No UI configuration found for client {client_id}, using default.")
        else:
            raise

    try:
        io_config = await _get_config(table_name="io_configs", client_id=client_id, model=IoConfiguration, local_db_pool=local_db_pool)
    except HTTPException as e:
        if e.status_code == 404:
            logger.warning(f"No IO configuration found for client {client_id}, using default.")
        else:
            raise

    try:
        opc_config = await _get_config(table_name="opc_configs", client_id=client_id, model=OpcConfiguration, local_db_pool=local_db_pool)
    except HTTPException as e:
        if e.status_code == 404:
            logger.warning(f"No OPC configuration found for client {client_id}, using default.")
        else:
            raise

    # io_config: IoConfiguration = await _get_config(table_name="io_configs", client_id=client_id, model=IoConfiguration, local_db_pool=local_db_pool)
    # opc_config: OpcConfiguration = await _get_config(table_name="opc_configs", client_id=client_id, model=OpcConfiguration, local_db_pool=local_db_pool)

    full_configuration = FullConfiguration(
        client_id=client_id,
        ui_configuration=ui_config,
        io_configuration=io_config,
        opc_configuration=opc_config
    )

    # updated_times = [c.lastUpdated for f, c in full_configuration.model_fields.items()].sort()
    updated_times = []
    for name, field in full_configuration.model_fields.items():
        field_value = getattr(full_configuration, name)
        if hasattr(field_value, "lastUpdated"):
            updated_times.append(getattr(field_value, "lastUpdated"))
    updated_times.sort()

    return ApiResponse(
        success=True,
            message=f"Configuration for client '{client_id}' retrieved successfully.",
            data=full_configuration.model_dump()
        )