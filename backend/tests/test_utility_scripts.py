# ./tests/test_utility_scripts.py
import pytest
import os
import subprocess
from pathlib import Path
import sys
from typing import Dict, Any

# Adjust sys.path to ensure 'backend' is recognized as a package root
current_dir = os.path.dirname(os.path.abspath(__file__))
backend_root = os.path.join(current_dir, '..')
sys.path.insert(0, backend_root)

# No more global GENERATED_MODELS_PATH or SCHEMA_FILE_PATH here,
# as the test will use tmp_path.


def test_generate_models_script_creates_file(tmp_path: Path): # NEW: Use tmp_path fixture
    """
    Test that generate_models.py creates the expected output file
    in a temporary directory and with correct content.
    """
    # Define paths relative to the temporary directory
    temp_config_dir = tmp_path / 'config'
    temp_autogenerated_dir = tmp_path / 'api' / 'autogenerated'
    temp_schema_file = temp_config_dir / 'schema.yml'
    temp_generated_models_file = temp_autogenerated_dir / 'generated_models.py'

    temp_config_dir.mkdir(parents=True)
    temp_autogenerated_dir.mkdir(parents=True)

    # Create a dummy schema.yml for testing in the temporary config directory
    dummy_schema_content = """
tables:
  temp_sensor_data:
    columns:
      time: TIMESTAMPTZ NOT NULL
      device_id: TEXT NOT NULL
    hypertable_column: time
  temp_config_data:
    columns:
      client_id: TEXT NOT NULL UNIQUE
      data_payload: JSONB
    hypertable_column: null
"""
    temp_schema_file.write_text(dummy_schema_content)

    # Run the generation script as a module, specifying temporary paths via environment variables
    # We must temporarily override the environment variables that generate_models.py uses
    # to point to our temporary files.
    original_schema_file_env = os.environ.get('SCHEMA_FILE_PATH')
    original_generated_models_dir_env = os.environ.get('GENERATED_MODELS_DIR')

    os.environ['SCHEMA_FILE_PATH'] = str(temp_schema_file)
    os.environ['GENERATED_MODELS_DIR'] = str(temp_autogenerated_dir)

    try:
        print("\n--- Running utilities.generate_models for utility test ---")
        result = subprocess.run(
            ['python', '-m', 'utilities.generate_models'],
            capture_output=True,
            text=True,
            check=True, # Raise an exception for non-zero exit codes
            cwd=backend_root # Still run from backend root to correctly find utilities module
        )
        print("--- generate_models.py stdout ---")
        print(result.stdout)
        print("--- generate_models.py stderr ---")
        print(result.stderr)
    except subprocess.CalledProcessError as e:
        pytest.fail(f"generate_models.py failed with error: {e.stderr}")
    finally:
        # Restore original environment variables
        if original_schema_file_env is not None:
            os.environ['SCHEMA_FILE_PATH'] = original_schema_file_env
        else:
            if 'SCHEMA_FILE_PATH' in os.environ:
                del os.environ['SCHEMA_FILE_PATH']
        
        if original_generated_models_dir_env is not None:
            os.environ['GENERATED_MODELS_DIR'] = original_generated_models_dir_env
        else:
            if 'GENERATED_MODELS_DIR' in os.environ:
                del os.environ['GENERATED_MODELS_DIR']


    assert temp_generated_models_file.exists(), "generated_models.py was not created in temp path."

    # Verify content of the generated file
    generated_content = temp_generated_models_file.read_text()
    assert "class TempSensorData(BaseModel):" in generated_content
    assert "    time: datetime" in generated_content
    assert "    device_id: str" in generated_content
    assert "class TempConfigData(BaseModel):" in generated_content
    assert "    client_id: str" in generated_content
    assert "    data_payload: Dict[str, Any]" in generated_content
    assert "DYNAMIC_TABLE_MODELS['temp_sensor_data'] = TempSensorData" in generated_content
    assert "DYNAMIC_TABLE_MODELS['temp_config_data'] = TempConfigData" in generated_content

    # The tmp_path fixture handles automatic cleanup of the temporary directory.
