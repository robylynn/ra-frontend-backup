# --- PostgreSQL to Python Type Mappings ---
TYPE_MAPPINGS = {
    "TEXT": "str",
    "TEXT NOT NULL": "str",
    "TEXT NOT NULL UNIQUE": "str",
    "INTEGER": "Optional[int]",
    "INTEGER NOT NULL": "int",
    "SMALLINT": "Optional[int]",
    "SMALLINT NOT NULL": "int",
    "DOUBLE PRECISION": "Optional[float]",
    "DOUBLE PRECISION NOT NULL": "float",
    "NUMERIC": "Optional[float]",
    "NUMERIC NOT NULL": "float",
    "BOOLEAN": "Optional[bool]",
    "BOOLEAN NOT NULL": "bool",
    "TIMESTAMPTZ": "Optional[datetime]",
    "TIMESTAMPTZ NOT NULL": "datetime",
    "TIMESTAMPTZ NOT NULL DEFAULT NOW()": "datetime",
    "JSONB": "Optional[Dict[str, Any]]",
    "JSONB NOT NULL": "Dict[str, Any]",
    "UUID": "Optional[UUID]",
    "UUID NOT NULL": "UUID",
    "UUID PRIMARY KEY DEFAULT gen_random_uuid()": "UUID",
}

# Special handling for tables with list-like columns (e.g., read_channels__0, read_channels__1)
SPECIAL_TABLE_LIST_FIELDS = {
    'analog_in_data': {
        'read_channels': 'List[bool]',
        'values': 'List[float]',
        'types': 'List[int]',
    },
    'digital_in_data': {
        'read_channels': 'List[bool]',
        'values': 'List[bool]',
    },
    'digital_out_data': {
        'write_channels': 'List[bool]',
        'values': 'List[bool]',
    }
}

# --- Pydantic Models for Schema Validation ---
class TableColumns(RootModel):
    """Represents the 'columns' section of a table schema."""
    root: Dict[str, str]

class TableDefinition(BaseModel):
    """Represents a single table's definition in the schema file."""
    columns: Dict[str, Any]
    hypertable_column: Optional[str] = Field(None, description="The column used as the TimescaleDB hypertable dimension.")
    number_of_tables: Optional[int] = None
    
class Schema(BaseModel):
    """Represents the entire schema.yml file structure."""
    tables: Dict[str, TableDefinition]


def postgres_type_to_python_type(pg_type: str) -> str:
    """
    Maps a PostgreSQL type string to a Python type string, handling common variations.
    """
    normalized_pg_type = pg_type.upper().strip()
    python_type = TYPE_MAPPINGS.get(normalized_pg_type)
    if python_type:
        return python_type
    
    if "JSONB" in normalized_pg_type:
        return "Dict[str, Any]" if "NOT NULL" in normalized_pg_type else "Optional[Dict[str, Any]]"
    if "UUID" in normalized_pg_type:
        if "PRIMARY KEY DEFAULT" in normalized_pg_type:
            return "UUID"
        return "UUID" if "NOT NULL" in normalized_pg_type else "Optional[UUID]"
    if "TIMESTAMPTZ" in normalized_pg_type:
        return "datetime" if "NOT NULL" in normalized_pg_type else "Optional[datetime]"

    logger.warning(
        f"No Python type mapping found for PostgreSQL type '{pg_type}'. Defaulting to 'Any'."
    )
    return "Any"


def generate_pydantic_models(schema_file: Path, output_file: Path):
    """
    Generates Pydantic BaseModel classes from a YAML schema definition.
    """
    logger.info(f"Starting Pydantic model generation from '{schema_file}'")

    if not schema_file.exists():
        logger.error(f"Schema file not found: {schema_file}")
        raise FileNotFoundError(f"Schema file not found: {schema_file}")

    with open(schema_file, "r") as f:
        schema_config_raw = yaml.safe_load(f)

    # Validate the loaded YAML against the Schema Pydantic model
    try:
        schema_config = Schema.model_validate(schema_config_raw)
        logger.info("Schema validation successful.")
    except ValidationError as e:
        logger.error("Schema validation failed!")
        logger.error(e)
        raise ValueError("Invalid schema.yml format.") from e

    models_code_lines: List[str] = [
        "# This file is auto-generated by utilities/generate_models.py",
        "# Do not edit this file manually.",
        "",
        "from pydantic import BaseModel, Field, computed_field, RootModel",
        "from datetime import datetime",
        "from typing import Dict, Any, Optional, List",
        "from uuid import UUID, uuid4",
        "import re",
        "",
        "# Dynamically created Pydantic models for each table",
        "",
        "DYNAMIC_TABLE_MODELS: Dict[str, type[BaseModel]] = {}",
        "SPECIAL_TABLE_LIST_FIELDS: Dict[str, Any] = {",
        "    'analog_in_data': {",
        "        'read_channels': 'List[bool]',",
        "        'values': 'List[float]',",
        "        'types': 'List[int]',",
        "    },",
        "    'digital_in_data': {",
        "        'read_channels': 'List[bool]',",
        "        'values': 'List[bool]',",
        "    },",
        "    'digital_out_data': {",
        "        'write_channels': 'List[bool]',",
        "        'values': 'List[bool]',",
        "    }",
        "}",
        "",
    ]

    for table_name, table_def in schema_config.tables.items():
        # Check if the table definition specifies a number of dynamic tables
        num_dynamic_tables = table_def.number_of_tables
        if num_dynamic_tables is not None:
            # Generate a single model for this dynamic table type
            class_name = "".join([part.capitalize() for part in table_name.split("_")])

            models_code_lines.append(f"class {class_name}(BaseModel):")
            models_code_lines.append(f"    \"\"\"")
            models_code_lines.append(f"    Pydantic model for the {table_name} table and its dynamic variants.")
            models_code_lines.append(f"    \"\"\"")

            columns = table_def.columns
            for col_name, pg_type in columns.items():
                python_type = postgres_type_to_python_type(pg_type)
                if pg_type.upper().strip() == "TIMESTAMPTZ NOT NULL DEFAULT NOW()":
                    models_code_lines.append(
                        f"    {col_name}: {python_type} = Field(default_factory=datetime.utcnow)"
                    )
                else:
                    models_code_lines.append(f"    {col_name}: {python_type}")

            models_code_lines.append("")
            models_code_lines.append("    def to_db_format(self) -> Dict[str, Any]:")
            models_code_lines.append("        '''")
            models_code_lines.append("        Returns a dictionary suitable for database insertion.")
            models_code_lines.append("        '''")
            models_code_lines.append("        return self.model_dump()")

            # Register the single model with all its dynamic table names
            for i in range(num_dynamic_tables):
                dynamic_table_name = f"{table_name}_{i}"
                models_code_lines.append(f"\nDYNAMIC_TABLE_MODELS['{dynamic_table_name}'] = {class_name}\n")

        # Handle other tables (list-based and single tables)
        else:
            class_name = "".join([part.capitalize() for part in table_name.split("_")])
            
            if table_name in SPECIAL_TABLE_LIST_FIELDS:
                models_code_lines.append(f"class {class_name}(BaseModel):")
                models_code_lines.append(f"    \"\"\"")
                models_code_lines.append(f"    Pydantic model for the {table_name} table.")
                models_code_lines.append(f"    It accepts a single list for each list-based field and automatically")
                models_code_lines.append(f"    converts it to the database's indexed columns.")
                models_code_lines.append(f"    \"\"\"")

                columns = table_def.columns
                if 'stamp' in columns:
                    models_code_lines.append(f"    stamp: datetime")

                for pydantic_field, pydantic_type in SPECIAL_TABLE_LIST_FIELDS[table_name].items():
                    models_code_lines.append(f"    {pydantic_field}: {pydantic_type}")
                
                models_code_lines.append("")
                models_code_lines.append("    def to_db_format(self) -> Dict[str, Any]:")
                models_code_lines.append("        '''")
                models_code_lines.append("        Returns a dictionary suitable for database insertion,")
                models_code_lines.append("        with list-based fields flattened into indexed columns.")
                models_code_lines.append("        '''")
                models_code_lines.append("        data_dict = self.model_dump()")
                models_code_lines.append(f"        keys_to_exclude = SPECIAL_TABLE_LIST_FIELDS.get('{table_name}', {{}}).keys()")
                models_code_lines.append("        return {key: value for key, value in data_dict.items() if key not in keys_to_exclude}")
                models_code_lines.append("\n")

                for pydantic_field, _ in SPECIAL_TABLE_LIST_FIELDS[table_name].items():
                    for i in range(8):
                        return_type = 'bool' if pydantic_field in ['read_channels', 'write_channels'] else 'float'
                        default_value = 'None'
                        models_code_lines.append(f"    @computed_field")
                        models_code_lines.append(f"    @property")
                        models_code_lines.append(f"    def {pydantic_field}__{i}(self) -> Optional[{return_type}]:")
                        models_code_lines.append(f"        return self.{pydantic_field}[{i}] if len(self.{pydantic_field}) > {i} else {default_value}\n")
            
            else:
                models_code_lines.append(f"class {class_name}(BaseModel):")
                columns = table_def.columns
                if not columns:
                    models_code_lines.append("    pass # No columns defined")
                
                for col_name, pg_type in columns.items():
                    python_type = postgres_type_to_python_type(pg_type)
                    if pg_type.upper().strip() == "UUID PRIMARY KEY DEFAULT gen_random_uuid()":
                        models_code_lines.append(
                            f"    {col_name}: {python_type} = Field(default_factory=uuid4)"
                        )
                    elif pg_type.upper().strip() == "TIMESTAMPTZ NOT NULL DEFAULT NOW()":
                        models_code_lines.append(
                            f"    {col_name}: {python_type} = Field(default_factory=datetime.utcnow)"
                        )
                    else:
                        models_code_lines.append(f"    {col_name}: {python_type}")
                
                models_code_lines.append("")
                models_code_lines.append("    def to_db_format(self) -> Dict[str, Any]:")
                models_code_lines.append("        '''")
                models_code_lines.append("        Returns a dictionary suitable for database insertion.")
                models_code_lines.append("        '''")
                models_code_lines.append("        return self.model_dump()")
            
            models_code_lines.append(f"\nDYNAMIC_TABLE_MODELS['{table_name}'] = {class_name}\n")
    
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, "w") as f:
        f.write("\n".join(models_code_lines))

    logger.info(f"Successfully generated Pydantic models to '{output_file}'.")


if __name__ == "__main__":
    try:
        generate_pydantic_models(Path(SCHEMA_FILE_PATH), Path(GENERATED_MODELS_FILE))
    except Exception as e:
        logger.error(f"Error during Pydantic model generation: {e}")
        sys.exit(1)
