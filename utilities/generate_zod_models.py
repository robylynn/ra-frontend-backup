def generate_zod_models(schema_file: Path, output_file: Path, template_path: Path):
    """
    Generates Zod schemas and TypeScript interfaces from a YAML schema definition
    using a Jinja2 template.
    """
    logger.info(f"Starting Zod model generation from '{schema_file}' using '{template_path}'.")

    if not schema_file.exists():
        logger.error(f"Schema file not found: {schema_file}")
        raise FileNotFoundError(f"Schema file not found: {schema_file}")

    with open(schema_file, "r") as f:
        raw_yaml_data = yaml.safe_load(f)

    # Setup Jinja2 environment
    env = Environment(loader=FileSystemLoader(template_path.parent))
    template = env.get_template(template_path.name)

    # Prepare data for the template
    # models = []
    # --- ADDED: New data structures for separating schema generation from map creation ---
    schemas_to_generate = []
    tables_for_map = []

    for table_name, table_def in raw_yaml_data.get("tables", {}).items():
        fields = []
        is_special_table = table_name in SPECIAL_TABLE_LIST_FIELDS

        # Handle all columns, including special and flattened fields
        columns = table_def.get("columns", {})
        
        # Add the core fields from the schema, filtering out old flattened fields
        for col_name, pg_type in columns.items():
            # Skip any fields that are part of the list-like columns or are old flattened fields
            if is_special_table and (col_name in SPECIAL_TABLE_LIST_FIELDS[table_name] or re.match(r'.+_\d+$', col_name)):
                continue
            
            fields.append({
                # "name": to_camel_case(col_name),
                "name": col_name,
                "zod_type": postgres_type_to_zod_type(pg_type),
                "ts_type": postgres_type_to_ts_type(pg_type),
            })
            
        if is_special_table:
            special_fields = SPECIAL_TABLE_LIST_FIELDS[table_name]
            for field_name, types in special_fields.items():
                # camel_field_name = to_camel_case(field_name)

                # Add the list-based field
                fields.append({
                    # "name": camel_field_name,
                    "name": field_name,
                    "zod_type": types["zod"],
                    "ts_type": types["ts"],
                })

                # Add the flattened fields with the correct __ naming convention
                for i in range(8):
                    flattened_field = f"{field_name}__{i}"
                    
                    fields.append({
                        "name": flattened_field,
                        "zod_type": f"{types['inner_zod']}.optional()",
                        "ts_type": f"{types['inner_ts']} | undefined",
                    })

        # models.append({
        #     "name": to_pascal_case(table_name),
        #     "table_name": table_name,
        #     "camel_case_name": to_camel_case(table_name),
        #     "fields": fields
        # })

        # # --- NEW LOGIC FOR NUMBERED TABLES ---
        # if "number_of_tables" in table_def:
        #     for i in range(table_def["number_of_tables"]):
        #         dynamic_table_name = f"{table_name}_{i}"
        #         models.append({
        #             "name": to_pascal_case(table_name), # The name of the Zod model remains the same
        #             "table_name": dynamic_table_name,   # But the table name in the map is specific
        #             "camel_case_name": to_camel_case(table_name),
        #             "fields": fields
        #         })
        # else:
        #     # Original logic for single tables
        #     models.append({
        #         "name": to_pascal_case(table_name),
        #         "table_name": table_name,
        #         "camel_case_name": to_camel_case(table_name),
        #         "fields": fields
        #     })
        # --- ADDED: Logic to populate the two new lists instead ---
        # Create a single model object to generate schema/types
        model_object = {
            "name": to_pascal_case(table_name),
            "camel_case_name": to_camel_case(table_name),
            "fields": fields
        }
        schemas_to_generate.append(model_object)
    
        # Logic for populating the TableSchemaMap entries
        if "number_of_tables" in table_def:
            for i in range(table_def["number_of_tables"]):
                tables_for_map.append({
                    "table_name": f"{table_name}_{i}",
                    "camel_case_name": to_camel_case(table_name),
                })
        else:
            tables_for_map.append({
                "table_name": table_name,
                "camel_case_name": to_camel_case(table_name),
            })
        
    # Render the template
    # rendered_code = template.render(models=models)
    rendered_code = template.render(
        schemas_to_generate=schemas_to_generate,
        tables_for_map=tables_for_map
    )

    # Write the output file
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, "w") as f:
        f.write(rendered_code)

    logger.info(f"Successfully generated Zod models and interfaces to '{output_file}'.")


