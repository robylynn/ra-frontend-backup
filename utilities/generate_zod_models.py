# --- Utility Functions ---
def to_camel_case(snake_case_str: str) -> str:
    """Converts a snake_case string to camelCase."""
    components = snake_case_str.split("_")
    return components[0] + "".join(x.title() for x in components[1:])

def to_pascal_case(snake_case_str: str) -> str:
    """Converts a snake_case string to PascalCase."""
    return "".join(x.title() for x in snake_case_str.split("_"))

def postgres_type_to_zod_type(pg_type: str) -> str:
    """Maps a PostgreSQL type string to a Zod type string."""
    normalized_pg_type = pg_type.upper().strip()
    return TYPE_MAPPINGS.get(normalized_pg_type, "z.any()")

def postgres_type_to_ts_type(pg_type: str) -> str:
    """Maps a PostgreSQL type string to a TypeScript type string."""
    normalized_pg_type = pg_type.upper().strip()
    return TS_TYPE_MAPPINGS.get(normalized_pg_type, "any")

