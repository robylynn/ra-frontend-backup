def execute_shell_command(command: str, timeout: int = 15):
    if not is_running_in_docker():
        command = "sudo " + command

    split_pattern = r'"([^"]*)"|(\S+)'
    raw_tokens = re.findall(split_pattern, command)
    clean_tokens = [item for sublist in raw_tokens for item in sublist if item]

    return subprocess.check_output(
        # command.split(' '),
        clean_tokens,
        text=True,
        stderr=subprocess.PIPE,
        timeout=timeout,
    )


def get_interfaces() -> NetworkInterfaces:
    output_string = execute_shell_command("nmcli dev show")

    # interfaces_by_type: Dict[str, List[str]] = {}
    interfaces: List[NetworkInterfaces] = []

    # Regex to find a block for a device. We'll capture the device name and the rest of the block.
    # The pattern looks for 'GENERAL.DEVICE:', captures the device name, and then captures
    # everything until the next 'GENERAL.DEVICE:' or the end of the string.
    device_blocks = re.findall(
        r"GENERAL\.DEVICE:\s+(.*?)\n(.*?)(?=\nGENERAL\.DEVICE:|\Z)",
        output_string,
        re.DOTALL,
    )

    for device_name, block in device_blocks:
        device_name = device_name.strip()

        # Use regex to find the GENERAL.TYPE line and capture the type.
        type_match = re.search(r"GENERAL\.TYPE:\s+(.+)", block)
        interface_type = type_match.group(1).strip() if type_match else "unknown"

        # Use regex to find the IP4.ADDRESS line and capture the IP address.
        # This will be None if no IP address is found.
        ip_match = re.search(r"IP4\.ADDRESS\[\d+\]:\s+([\d.]+)", block)
        ip_address = ip_match.group(1).strip() if ip_match else None

        subnet_match = re.search(r"IP4\.ADDRESS\[1\]:.*?\/(\d+)", block)
        subnet_mask = (
            str(
                ipaddress.IPv4Network(
                    f'{"0.0.0.0"}/{subnet_match.group(1).strip()}', strict=False
                ).netmask
            )
            if subnet_match
            else None
        )
        # subnet_mask = subnet_match.group(1).strip() if subnet_match else None

        # Use regex to find the SSID for wireless interfaces.
        ssid = None
        if interface_type == "wifi":
            ssid_match = re.search(r"GENERAL\.CONNECTION:\s+(.+)", block)
            if ssid_match and ssid_match.group(1).strip() != "--":
                ssid = ssid_match.group(1).strip()

        interfaces.append(
            NetworkInterfaceDefinition(
                name=device_name,
                type=interface_type,
                subnet_mask=subnet_mask,
                address=ip_address,
                ssid=ssid,
            )
        )

    return NetworkInterfaces(interfaces=interfaces)


def connected_ssids() -> List[str]:
    interfaces = get_interfaces()
    return [
        interface.ssid
        for interface in interfaces.interfaces
        if interface.ssid is not None
    ]


def wifi_interface_names() -> List[str]:
    interfaces = get_interfaces()
    return [
        interface.name
        for interface in interfaces.interfaces
        if interface.type == "wifi"
    ]


def ethernet_interface_names() -> List[str]:
    interfaces = get_interfaces()
    return [
        interface.name
        for interface in interfaces.interfaces
        if interface.type == "ethernet"
    ]


def get_interface_ip(interface_name: str) -> str | None:
    interfaces = get_interfaces()
    return interfaces.get_interface_ip(interface_name=interface_name)


def get_default_wifi_adapter() -> str | None:
    wifi_interfaces = wifi_interface_names()
    if len(wifi_interfaces) > 0:
        return wifi_interfaces[0]
    return None


