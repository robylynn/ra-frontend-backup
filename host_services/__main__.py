@ra_host_service_server.post("/connect_wifi")
def connect_wifi(ssid: str, password: str) -> ApiResponse:
    try:
        active_ssids = connected_ssids()
        # Assume only one connection
        if len(active_ssids) > 0 and ssid in active_ssids:
            return ApiResponse(
                success=False, message=f"Wi-Fi already connected to {ssid}"
            )

        output = execute_shell_command(
            f'nmcli dev wifi connect "{ssid}" password "{password}"', timeout=40
        )

        connect_output = [line.strip() for line in output.splitlines() if line.strip()]
        if any(["successfully activated" in s for s in connect_output]):
            logger.info(f"Connected to network '{ssid}'.")
            return ApiResponse(success=True, data={"connect_success": True})
        else:
            return ApiResponse(success=False, data={"connect_success": False})

    except subprocess.CalledProcessError as e:
        error_details = HostServicesError(
            description=f"Subprocess error when connecting to Wi-Fi network {ssid}",
            details=str(e),
            stderr=e.stderr,
        )
    except Exception as e:
        error_details = HostServicesError(
            description=f"Failed to connect to Wi-Fi network {ssid}",
            details=f"{e}",
        )
    logger.info(
        f"Failed to connect to network '{ssid}', details: {error_details.model_dump()}"
    )
    return ApiResponse(success=False, data=error_details)


@ra_host_service_server.post("/set_interface_settings")
def set_interface_ip(interface_settings: InterfaceSettings) -> ApiResponse:
    static_connection_name = "_".join([interface_settings.interface_name, "static"])

    # First delete any existing connection profile
    command_string = f"nmcli connection delete {static_connection_name}"
    try:
        execute_shell_command(command_string)
    except Exception as e:
        logger.warning(f"Error deleting connection {static_connection_name}: {e}")

    command_string = [
        f"nmcli connection add type ethernet con-name {static_connection_name} ifname {interface_settings.interface_name}"
    ]

    if interface_settings.method == "auto":
        command_string.extend(["ipv4.method", f"{interface_settings.method}"])
    else:
        command_string.extend(["ipv4.method", "manual"])

        # Validate IP settings
        try:
            cidr_network = ipaddress.IPv4Network(
                address=f"{interface_settings.ipv4_address}/{interface_settings.subnet_mask}",
                strict=False,
            )
            gateway_address = (
                ipaddress.IPv4Address(interface_settings.gateway)
                if interface_settings.gateway
                else None
            )
            dns_address = (
                ipaddress.IPv4Address(address=interface_settings.dns)
                if interface_settings.dns
                else None
            )
        except Exception as e:
            error_details = HostServicesError(
                description=f"IP validation failed for {interface_settings.model_dump()}",
                details=f"{e}",
            )
            return ApiResponse(success=False, data=error_details)

        command_string.extend(
            [
                "ipv4.addresses",
                f"{interface_settings.ipv4_address}/{cidr_network.prefixlen}",
            ]
        )

        if gateway_address:
            command_string.extend(["ipv4.gateway", f"{gateway_address}"])

        if dns_address:
            command_string.extend(["ipv4.dns", f"{dns_address}"])

        if interface_settings.autoconnect:
            command_string.extend(["connection.autoconnect", "yes"])

    try:
        execute_shell_command(" ".join(command_string))

        try:
            execute_shell_command(f"nmcli dev down {interface_settings.interface_name}")
        except Exception as e:
            logger.warning(
                f"Error bringing down interface {interface_settings.interface_name}: {e}"
            )

        execute_shell_command(f"nmcli connection up {static_connection_name}")

        logger.info(
            f"Changed interface settings for {interface_settings.interface_name} to {interface_settings.model_dump()}"
        )
        return ApiResponse(
            success=True,
        )

    except subprocess.CalledProcessError as e:
        error_details = HostServicesError(
            description=f"Subprocess error when modifying interface {interface_settings.interface_name}",
            details=str(e),
            stderr=e.stderr,
        )
    except Exception as e:
        error_details = HostServicesError(
            description=f"Failed to modify interface '{interface_settings.interface_name}'",
            details=f"{e}",
        )

    logger.error(
        f"Failed to modify interface '{interface_settings.interface_name}', details: {error_details.model_dump()}"
    )

    return ApiResponse(
        success=False,
        message=f"Failed to modify interface '{interface_settings.interface_name}'",
        data=error_details,
    )


